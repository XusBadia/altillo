#!/usr/bin/env python3
"""Converts the exported Home states (/tmp/casa-ui/{es,en}/*.png, from HomeExportTests.swift) to WebP in
public/casa/ui (lossy colour at q 92, lossless alpha: ~10× smaller than the 3× PNGs) and measures what the video needs, in points (@3x): the opaque box of each notch shape and the doorbell camera's thumbnail.
Writes src/casa/manifest.ts.

Usage: python3 scripts/casa-manifest.py [--from /tmp/casa-ui]
"""
import json
import pathlib
import subprocess
import sys

import numpy as np
from PIL import Image

root = pathlib.Path(__file__).resolve().parents[1]
ui = root / 'public/casa/ui'
src = pathlib.Path(sys.argv[sys.argv.index('--from') + 1]) if '--from' in sys.argv else pathlib.Path('/tmp/casa-ui')

if src.exists():
    for lang in ('es', 'en'):
        if (src / lang).exists():
            (ui / lang).mkdir(parents=True, exist_ok=True)
            pngs = [p for p in sorted((src / lang).glob('*.png')) if not p.stem.startswith('demo-')]
            procs = []
            for png in pngs:
                procs.append(subprocess.Popen(['cwebp', '-quiet', '-q', '92', '-alpha_q', '100', '-m', '6', '-sharp_yuv',
                                               str(png), '-o', str(ui / lang / f'{png.stem}.webp')]))
                if len(procs) >= 8:
                    for p in procs:
                        assert p.wait() == 0
                    procs = []
            for p in procs:
                assert p.wait() == 0
            for old in (ui / lang).glob('*.png'):
                old.unlink()

SHAPES = ['idle', 'grid', 'peekDoorbell', 'blind-00', 'lamp-off', 'settings', 'settings-connected']
boxes, thumbs = {}, {}
for lang in ('es', 'en'):
    for name in SHAPES:
        png = ui / lang / f'{name}.webp'
        if not png.exists():
            continue
        a = np.asarray(Image.open(png).convert('RGBA'))
        alpha = a[..., 3] > 40
        if name.startswith('settings'):
            # The card: last row that isn't the plain wood background.
            rgb = a[..., :3].astype(int)
            diff = np.abs(rgb - rgb[-4, 4]).sum(-1) > 12
            rows = np.where(diff.any(1))[0]
            boxes.setdefault(name, {})[lang] = [0, 0, round(a.shape[1] / 3, 1), round((rows.max() + 1) / 3, 1)]
            continue
        # Opaque black body only (the soft shadow around it is semi-transparent).
        solid = a[..., 3] > 250
        ys, xs = np.where(solid)
        boxes.setdefault(name, {})[lang] = [round(xs.min() / 3, 1), 0.0, round((xs.max() + 1) / 3, 1), round((ys.max() + 1) / 3, 1)]
        if name == 'peekDoorbell':
            # The camera thumbnail: the bright-ish block left of the title, on the second line.
            body = a[..., :3].astype(int).sum(-1)
            y0, y1 = int(25 * 3), int(60 * 3)
            region = body[y0:y1, :] > 120
            cols = np.where(region.any(0))[0]
            # First run of columns from the left inside the shape.
            run = [cols[0]]
            for c in cols[1:]:
                if c - run[-1] > 3:
                    break
                run.append(c)
            x0, x1 = run[0], run[-1] + 1
            rows = np.where(region[:, x0:x1].any(1))[0]
            thumbs[lang] = [round(x0 / 3, 1), round((y0 + rows.min()) / 3, 1), round(x1 / 3, 1), round((y0 + rows.max() + 1) / 3, 1)]

out = ('// Generated by scripts/casa-manifest.py: [x0, y0, x1, y1] in points.\n'
       f'export const CASA_BOXES: Record<string, Record<string, [number, number, number, number]>> = {json.dumps(boxes)};\n'
       f'export const CASA_THUMB: Record<string, [number, number, number, number]> = {json.dumps(thumbs)};\n')
(root / 'src/casa/manifest.ts').write_text(out)
print(json.dumps(boxes, indent=0), json.dumps(thumbs))
