export function createDemoCopy(locale) {
  const isEnglish = String(locale).toLowerCase().startsWith('en');
  function t(value) {
    if (!isEnglish || !value.trim()) return value;
    const key = value.trim().replace(/\s+/g, ' ');
    let translated = english[key];
    if (!translated) {
      translated = key
        .replace(/^(\d+) archivo recibido$/, '$1 file received')
        .replace(/^(\d+) archivos recibidos$/, '$1 files received')
        .replace(/, en el estante$/, ', on the shelf')
        .replace(/, documento de ejemplo$/, ', sample document')
        .replace(/^Retirar (.+)$/, 'Remove $1')
        .replace(/^(.+) añadido al estante\.$/, '$1 added to the shelf.')
        .replace(/^(.+) retirado del estante\.$/, '$1 removed from the shelf.')
        .replace(/^(.+) llevado a Entregas\.$/, '$1 moved to Deliveries.')
        .replace(/^(.+)\. Arrástralo a Entregas o usa «Llevar a Entregas»\.$/, '$1. Drag it to Deliveries or choose “Move to Deliveries”.')
        .replace(/^(.+): (\d+)% consumido$/, '$1: $2% used')
        .replace(/^Consumo semanal de (.+)$/, '$1 weekly usage')
        .replace(/^Se repone en (.+)$/, 'Resets in $1');
    }
    return value.replace(value.trim(), translated);
  }
  function localize(root) {
    if (!isEnglish) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (!node.parentElement.closest('code')) node.nodeValue = t(node.nodeValue);
    }
    root.querySelectorAll('[aria-label]').forEach((node) => {
      node.setAttribute('aria-label', t(node.getAttribute('aria-label')));
    });
  }
  return { t, localize };
}
