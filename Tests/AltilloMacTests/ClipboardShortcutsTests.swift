    @Test func historyStaysInMemoryUnlessTheUserAsksToKeepIt() throws {
        let defaults = Self.makeDefaults()
        let archive = Self.scratchArchive()
        defer { try? FileManager.default.removeItem(at: archive.url.deletingLastPathComponent()) }

        let (store, pasteboard) = Self.makeStore(defaults: defaults, archive: archive)
        defer { pasteboard.releaseGlobally() }
        #expect(!store.keepsHistory, "off by default")
        Self.put("secret-ish note", on: pasteboard)
        store.check()
        store.stop()
        #expect(!FileManager.default.fileExists(atPath: archive.url.path), "nothing on disk while it's off")

        store.keepsHistory = true
        #expect(defaults.bool(forKey: ClipboardStore.keepsHistoryKey))
        #expect(FileManager.default.fileExists(atPath: archive.url.path))
        let permissions = try FileManager.default.attributesOfItem(atPath: archive.url.path)[.posixPermissions] as? Int
        #expect(permissions == 0o600)
        #expect(archive.load()?.items.map(\.text) == ["secret-ish note"])

        // A new launch with the option on finds it again.
        let (relaunched, other) = Self.makeStore(defaults: defaults, archive: archive)
        defer { other.releaseGlobally() }
        #expect(relaunched.keepsHistory)
        relaunched.start()
        #expect(relaunched.history.items.map(\.text) == ["secret-ish note"])
        relaunched.keepsHistory = false
        #expect(!FileManager.default.fileExists(atPath: archive.url.path), "turning it off deletes the file")
        relaunched.stop()
        #expect(relaunched.history.isEmpty, "turning the section off forgets what's in memory")
    }

    @Test func theWatcherFollowsTheSection() async throws {
        let settings = AltilloSettings(defaults: Self.makeDefaults())
        let (store, pasteboard) = Self.makeStore()
        defer { pasteboard.releaseGlobally() }
        settings.setEnabled(.clipboard, false)
        store.follow(settings)
        #expect(!store.isWatching, "opt-in: nothing is watched while the section is off")

        settings.setEnabled(.clipboard, true)
        for _ in 0..<100 where !store.isWatching { try await Task.sleep(for: .milliseconds(10)) }
        #expect(store.isWatching)

        settings.setEnabled(.clipboard, false)
        for _ in 0..<100 where store.isWatching { try await Task.sleep(for: .milliseconds(10)) }
        #expect(!store.isWatching, "turning the section off stops the timer")
    }

