        for text in ["one", "two", "three"] {
            Self.put(text, on: pasteboard)
            store.check()
        }
        let pinned = store.history.items.first { $0.text == "two" }!
        store.togglePin(pinned)

        store.clear()
        #expect(store.history.items.map(\.text) == ["two"])
        #expect(store.undoable?.kind == .clear)
