    /// Everything a fake `shortcuts` was asked to do.
    private actor Calls {
        private(set) var arguments: [[String]] = []
        private(set) var inputs: [String] = []
        func add(_ call: [String]) {
            arguments.append(call)
            if let index = call.firstIndex(of: "--input-path"), call.indices.contains(index + 1),
               let text = try? String(contentsOfFile: call[index + 1], encoding: .utf8) {
                inputs.append(text)
            }
        }
    }

    private static func makeShortcuts(
        _ list: [ShortcutInfo],
        calls: Calls,
        defaults: UserDefaults = makeDefaults(),
        result: ShortcutsCLI.Output = .init(status: 0, standardOutput: "Done!\n", standardError: "")
    ) -> ShortcutsStore {
        ShortcutsStore(
            defaults: defaults,
            lister: { list },
            runner: { arguments in
                await calls.add(arguments)
                return result
            }
        )
    }

    @Test func runningReportsSuccessFailureAndCleansTheInputUp() async throws {
        let calls = Calls()
        let coffee = ShortcutInfo(name: "Coffee", identifier: "AAAAAAAA-0000-0000-0000-000000000001")
        let store = Self.makeShortcuts([coffee], calls: calls)
        await store.loadIfNeeded()
        #expect(store.phase == .ready)

        let state = await store.run(coffee, input: .text("Hola, Ana", label: "the clipboard’s text"))
        #expect(state == .succeeded(output: "Done!"))
        #expect(store.runs[coffee.id] == .succeeded(output: "Done!"))
        #expect(store.lastOutcome?.shortcut == coffee)
        let arguments = await calls.arguments
        #expect(arguments.count == 1)
        #expect(arguments[0].first == "run" && arguments[0].last == coffee.identifier)
        #expect(await calls.inputs == ["Hola, Ana"], "the text reached the shortcut as a file")
        let path = try #require(arguments[0].firstIndex(of: "--input-path").map { arguments[0][$0 + 1] })
        #expect(!FileManager.default.fileExists(atPath: path), "the input file is gone afterwards")

        let failing = Self.makeShortcuts([coffee], calls: Calls(),
                                         result: .init(status: 1, standardOutput: "", standardError: "Error: Nope"))
        #expect(await failing.run(coffee) == .failed("Nope"))
    }

