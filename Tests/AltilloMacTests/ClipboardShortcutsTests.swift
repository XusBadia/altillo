    private static func makeDefaults(_ name: String = #function) -> UserDefaults {
        TestDefaultsJanitor.purgeStale()
        let suite = "me.badia.altillo.tests.clipshort.\(name.replacingOccurrences(of: "()", with: ""))-\(UUID().uuidString)"
        UserDefaults.standard.removePersistentDomain(forName: suite)
        return UserDefaults(suiteName: suite)!
    }

    private static func scratchArchive() -> ClipboardArchive {
        ClipboardArchive(url: FileManager.default.temporaryDirectory
            .appendingPathComponent("altillo-clipboard-tests-\(UUID().uuidString)/history.json"))
    }

    /// A store on a pasteboard of its own, with the frontmost app decided by the test.
    private static func makeStore(
        frontmost: String? = "com.apple.TextEdit",
        defaults: UserDefaults = makeDefaults(),
        archive: ClipboardArchive = scratchArchive()
    ) -> (ClipboardStore, NSPasteboard) {
        let pasteboard = NSPasteboard.withUniqueName()
        let store = ClipboardStore(pasteboard: pasteboard, defaults: defaults, archive: archive,
                                   frontmostBundleID: { frontmost })
        return (store, pasteboard)
    }

    private static func put(_ text: String, on pasteboard: NSPasteboard, marking extra: [String] = [],
                            source: String? = nil) {
        var types: [NSPasteboard.PasteboardType] = [.string] + extra.map { .init($0) }
        if source != nil { types.append(.init(ClipboardPrivacy.sourceType)) }
        pasteboard.declareTypes(types, owner: nil)
        pasteboard.setString(text, forType: .string)
        for type in extra { pasteboard.setString("", forType: .init(type)) }
        if let source { pasteboard.setString(source, forType: .init(ClipboardPrivacy.sourceType)) }
    }

